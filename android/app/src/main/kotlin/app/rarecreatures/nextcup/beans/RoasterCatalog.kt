/**
 * The bundled roaster catalog (`catalog.json`, shared with iOS): facts about real roasters and coffees with the
 * date they were checked. Starting recipes are generated by StarterRecipes, never stored in the file.
 */
@Serializable
data class RoasterCatalog(val version: Int, val checkedOn: String, val note: String, val roasters: List<CatalogRoaster>) {
    companion object {
        private val json = Json { ignoreUnknownKeys = true }

        /** Parses and validates: unknown roast levels, duplicate keys or non-https links fail, so a bad bundle fails in tests. */
        fun parse(text: String): RoasterCatalog {
            val catalog = json.decodeFromString(serializer(), text)
            val keys = mutableSetOf<String>()
            for (r in catalog.roasters) {
                require(r.name.isNotEmpty() && r.website.startsWith("https://") && keys.add(r.key)) { "roaster ${r.key}" }
                for (c in r.coffees) {
                    require(c.name.isNotEmpty() && keys.add(c.key) && (c.source?.startsWith("https://") ?: true)) { "coffee ${c.key}" }
                    require(c.roastLevel == null || rawOf<RoastLevel>(c.roastLevel) != null) { "roast level ${c.roastLevel}" }
                }
            }
            return catalog
        }
    }
}

@Serializable
data class CatalogRoaster(
    val key: String, val name: String, val city: String, val region: String, val country: String, val website: String, val kind: String,
    val coffees: List<CatalogCoffee>,
) {
    val place: String get() = "$city, $region"
}

@Serializable
data class CatalogCoffee(
    val key: String, val name: String, val originCountry: String? = null, val region: String? = null, val process: String? = null,
    val roastLevel: String? = null, val isBlend: Boolean, val isDecaf: Boolean, val flavorNotes: List<String>? = null, val source: String? = null,
) {
    val starterRecipes: List<StarterRecipe> get() = StarterRecipes.recipes(StarterRoast.of(roastLevel), process)
}

/** Adds a catalog coffee to the library and keeps the starter recipe a brew uses; both reuse what exists. */
class CatalogService(private val db: NextCupDatabase) {
    /** The bean for a catalog coffee: an existing one with the same name and roaster, or a new one. */
    suspend fun addBean(coffee: CatalogCoffee, roaster: CatalogRoaster): Pair<Bean, Boolean> {
        val roasters = db.roasters().all()
        db.beans().all().firstOrNull { b ->
            b.name.equals(coffee.name, true) && roasters.firstOrNull { it.id == b.roasterId }?.name.equals(roaster.name, true)
        }?.let { return it to false }
        val bean = BeanService(db).save(
            BeanFields(
                name = coffee.name, roasterName = roaster.name, roasterCity = roaster.city, roasterWebsite = roaster.website,
                originCountry = coffee.originCountry ?: "", region = coffee.region ?: "", process = coffee.process ?: "",
                roastLevel = rawOf<RoastLevel>(coffee.roastLevel), flavorNotes = coffee.flavorNotes.orEmpty().joinToString(", "), isDecaf = coffee.isDecaf,
            ),
        )
        return bean to true
    }

    /** The saved recipe for a starter recipe of this coffee (or of a bean), created on first use. */
    suspend fun recipe(starter: StarterRecipe, key: String, coffeeName: String): Recipe {
        val builtInKey = "starter.$key.${starter.style.raw}"
        db.recipes().all().firstOrNull { it.builtInKey == builtInKey }?.let { return it }
        val method = db.methods().all().firstOrNull { it.builtInKey == starter.methodKey }
        val recipe = Recipe(
            name = "$coffeeName: ${starter.name}", doseG = starter.doseG, waterG = starter.waterG, tempC = starter.tempC,
            totalTimeS = starter.totalTimeS, tuningNote = starter.note, credit = "Next Cup starting recipe", builtInKey = builtInKey, methodId = method?.id,
        )
        db.recipes().replaceSteps(
            recipe,
            starter.steps.mapIndexed { i, s ->
                RecipeStep(order = i, kind = rawOf<StepKind>(s.kind) ?: StepKind.POUR, startOffsetS = s.startOffsetS, targetCumulativeWaterG = s.targetCumulativeWaterG, instruction = s.instruction)
            },
        )
        return recipe
    }
}
